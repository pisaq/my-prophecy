/** Step values 0–125; 126 = Reset (loop end). */
export const GATED_STEP_RESET = 126;

function gatedStepParams() {
  const out = [];
  for (let track = 1; track <= 4; track++) {
    for (let step = 1; step <= 16; step++) {
      out.push({
        id: `seq_t${track}_s${step}`,
        label: `T${track} S${step}`,
        group: 'sequencer',
        nrpn: 192 + (track - 1) * 16 + (step - 1),
        min: 0,
        max: GATED_STEP_RESET,
        type: 'continuous',
        defaultValue: 0,
        seqTrack: track,
        seqStep: step,
      });
    }
  }
  return out;
}


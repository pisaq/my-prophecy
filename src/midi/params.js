/** Map a UI/NRPN-range value to a 0–127 CC value when ranges differ. */
export function toCcValue(param, value) {
  const max = param.ccMax ?? param.max;
  if (max === param.max) return Math.round(clamp(value, param.min, max));
  const t = (value - param.min) / (param.max - param.min || 1);
  return Math.round(clamp(t * 127, 0, 127));
}

export function fromCcValue(param, ccValue) {
  const max = param.ccMax ?? param.max;
  if (max === param.max) return clamp(ccValue, param.min, max);
  const t = ccValue / 127;
  return Math.round(param.min + t * (param.max - param.min));
}

function clamp(n, min, max) {
  return Math.min(max, Math.max(min, n));
}

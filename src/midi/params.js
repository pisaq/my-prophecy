/**
 * Per-layer patch params (Layer A and B each have their own value).
 * Excludes patch-wide globals (A/B mode) and performance / synth-wide controls.
 */
export function isLayerParam(param) {
  return (
    !!param &&
    !param.special &&
    !param.global &&
    param.id !== 'mod_wheel' &&
    param.id !== 'master_volume'
  );
}

